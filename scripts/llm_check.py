"""Live check of the Gemini explainer against the output guardrail.

    python scripts/llm_check.py        # needs GEMINI_API_KEY in .env or the environment

Runs every answerable case from eval/cases.json through the agent with Gemini
writing the explanation, then reports how many explanations passed the output
guardrail, how many were rejected (and why), and how many API calls failed.
Writes eval/llm_results.md. Results vary run to run because the LLM does.
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.agent import VibeAgent  # noqa: E402
from src.explainer import get_explainer  # noqa: E402


DELAY_SECONDS = 5  # the free tier allows only a few requests per minute


def main() -> int:
    explainer = get_explainer()
    if explainer.name != "gemini":
        print("GEMINI_API_KEY is not set (or google-genai is not installed). Nothing to check.")
        return 1
    cases = [c for c in json.loads((ROOT / "eval" / "cases.json").read_text()) if c["expect"].get("status") == "ok"]
    agent = VibeAgent(explainer=explainer, k=3)
    rows, counts = [], {"gemini": 0, "rejected": 0, "api_error": 0}
    for i, case in enumerate(cases):
        if i:
            time.sleep(DELAY_SECONDS)
        started = time.perf_counter()
        result = agent.run(case["query"])
        seconds = time.perf_counter() - started
        steps = {t["name"]: t for t in result.trace}
        rejected = [t for t in result.trace if t["name"] == "output_guardrail" and t.get("problems")
                    and "rejected" in t["detail"]]
        if result.explainer == "gemini":
            outcome, why = "gemini text shown", ""
            counts["gemini"] += 1
        elif rejected:
            outcome, why = "rejected -> template", "; ".join(rejected[0]["problems"])
            counts["rejected"] += 1
        else:
            outcome, why = "API error -> template", steps.get("explain", {}).get("detail", "")[:90]
            counts["api_error"] += 1
        rows.append((case["id"], outcome, why, f"{seconds:.1f}s"))
        print(f"{case['id']:14} {outcome:22} {why}")

    total = len(rows)
    summary = (f"{counts['gemini']}/{total} Gemini explanations passed the output guardrail, "
               f"{counts['rejected']} rejected, {counts['api_error']} API errors.")
    print("\n" + summary)
    md = ["# Live Gemini check", "", f"Generated by `python scripts/llm_check.py` on {time.strftime('%Y-%m-%d')} "
          f"with `{explainer._model}`. LLM output varies, so rerunning can change these numbers.", "",
          "| case | outcome | guardrail problems / error | time |", "|---|---|---|---|"]
    md += [f"| {a} | {b} | {c.replace('|', '/') or '-'} | {d} |" for a, b, c, d in rows]
    md += ["", f"**Summary:** {summary}", ""]
    (ROOT / "eval" / "llm_results.md").write_text("\n".join(md), encoding="utf-8")
    print("wrote eval/llm_results.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
